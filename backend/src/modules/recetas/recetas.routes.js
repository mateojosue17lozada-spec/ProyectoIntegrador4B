const express=require("express");
const auth=require("../../middleware/auth.middleware");
const rol=require("../../middleware/rol.middleware");
const responder=require("../../utils/http");
const service=require("./recetas.service");
const router=express.Router();
router.use(auth);
router.get("/",responder(()=>service.listar()));
router.get("/pedidos",responder(()=>service.listarPedidos()));
router.get("/laboratorios",responder(()=>service.laboratorios()));
router.post("/laboratorios",rol(["Administrador"]),responder(req=>service.crearLaboratorio(req.body),201));
router.put("/laboratorios/:id",rol(["Administrador"]),responder(req=>service.actualizarLaboratorio(req.params.id,req.body)));
router.delete("/laboratorios/:id",rol(["Administrador"]),responder(req=>service.eliminarLaboratorio(req.params.id)));
router.post("/pedidos",rol(["Administrador","Optometra","Vendedor"]),responder(req=>service.crearPedido(req.body),201));
router.put("/pedidos/:id",rol(["Administrador","Vendedor"]),responder(req=>service.actualizarPedido(req.params.id,req.body)));
router.get("/:id",responder(req=>service.obtener(req.params.id)));
router.post("/",rol(["Administrador","Optometra"]),responder(req=>service.crear(req.body,req.usuario,req),201));
router.post("/:id/imprimir",responder(req=>service.marcarImpresa(req.params.id,req.usuario,req)));
module.exports=router;
